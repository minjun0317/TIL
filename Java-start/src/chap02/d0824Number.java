package chap02;

public class d0824Number {
    static void main(String[] args) {
        int mach = 340;
        int distance;

        distance = mach * 60 * 60;
        System.out.println("소리가 1시간 동안 가는 거리 : "+distance+"m");

        double r;
        double area;

        r = 10.0;
        area = r * r * 3.14;

        System.out.println("반지름이 "+r+"인 원의 넓이 :"+area);
    }
}
