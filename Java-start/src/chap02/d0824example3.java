package chap02;

public class d0824example3 {
    static void main(String[] args) {
        int f1 = 15;
        System.out.println(f1);

        byte f2 = 0b1111;
        System.out.println(f2);

        short f3 = 017;
        System.out.println(f3);

        int f4 = 0xF;
        System.out.println(f4);

        long f5 = 30000L;
        System.out.println(f5);

        double half1 = 0.5;
        System.out.println("half = " + half1); // soutv

        double half2 = 5E-1;
        System.out.println("half2 = " + half2);
        
        float pil = 3.141592F;
        System.out.println("pil = " + pil);

        //상수
        final int A = 10;
        System.out.println(A);
    }
}
